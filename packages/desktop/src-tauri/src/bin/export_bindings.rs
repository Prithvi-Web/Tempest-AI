//! `make gen-contracts` runs this to (re)write the committed Boundary B bindings. The drift
//! gate diffs the output — a schema change that is not regenerated turns CI red.

use std::path::PathBuf;

fn main() {
    let target = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/generated/bindings.ts");
    tempest_desktop_lib::specta_builder()
        .export(
            // No BigInt-style types cross this boundary: the domain schema pins every integer
            // to int32 (local SQLite ids and per-run counts), so everything exports as `number`.
            specta_typescript::Typescript::default()
                .header("// Generated by tauri-specta via `make gen-contracts` — do not edit.\n"),
            &target,
        )
        .expect("bindings export must succeed");
    println!("gen-bindings: {}", target.display());
}
