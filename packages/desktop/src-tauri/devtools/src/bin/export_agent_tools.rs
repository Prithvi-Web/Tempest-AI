//! Boundary D generator (CLAUDE.md §9c, ADR-0035): `make gen-contracts` runs this to (re)write
//! the committed Agent Tool Protocol artifacts. The drift gate diffs them — a tool added or an
//! argument changed without regenerating turns CI red, exactly as it does for boundaries A/B/C.
//!
//! One Rust source, three outputs:
//!   * `packages/shared-schema/agent-tools.json`      — canonical manifest (the contract)
//!   * `packages/shared-schema/agent-tools.anthropic.json` — model-facing, Anthropic envelope
//!   * `packages/shared-schema/agent-tools.openai.json`    — model-facing, OpenAI envelope
//!   * `packages/desktop/src/generated/agentTools.ts` — the webview's typed view
//!
//! The two model-facing files are committed on purpose. They are what actually reaches a
//! provider, so a change in what the model is told must be *visible in review* rather than
//! computed silently at runtime (L17's spirit: narration and evidence stay legible).

use std::path::{Path, PathBuf};

use tempest_desktop_lib::agent_tools;

fn write(path: &Path, body: &str) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("generated directory must be creatable");
    }
    std::fs::write(path, body).unwrap_or_else(|err| panic!("write {}: {err}", path.display()));
    println!("gen-agent-tools: {}", path.display());
}

/// Pretty JSON with a trailing newline — deterministic bytes so the drift gate compares content,
/// never formatting noise.
fn json(value: &serde_json::Value) -> String {
    let mut body = serde_json::to_string_pretty(value).expect("serialisable");
    body.push('\n');
    body
}

/// The webview needs the tool names and their policy (the approval UI is driven by it), not the
/// argument schemas — those are for the model. Emitting a typed const beats shipping the whole
/// manifest into the bundle.
fn typescript(manifest: &[agent_tools::ToolSpec]) -> String {
    let mut out = String::from(
        "// Generated by `make gen-contracts` (Boundary D — Agent Tool Protocol). Do not edit.\n\
         // Source of truth: packages/desktop/src-tauri/src/agent_tools.rs\n\n\
         export type Approval = \"auto\" | \"prompt_once_per_project\" | \"always_prompt\";\n\
         export type WriteScope = \"none\" | \"shadow_worktree\";\n\n\
         export type ToolPolicy = {\n  approval: Approval;\n  touchesNetwork: boolean;\n  \
         destructive: boolean;\n  writes: WriteScope;\n};\n\n\
         export type AgentToolName =\n",
    );
    for tool in manifest {
        out.push_str(&format!("  | \"{}\"\n", tool.name));
    }
    out.push_str(";\n\nexport const AGENT_TOOLS: ReadonlyArray<{\n  name: AgentToolName;\n  description: string;\n  policy: ToolPolicy;\n}> = [\n");
    for tool in manifest {
        let approval = serde_json::to_string(&tool.policy.approval).expect("enum serialises");
        let writes = serde_json::to_string(&tool.policy.writes).expect("enum serialises");
        let description = serde_json::to_string(&tool.description).expect("string serialises");
        out.push_str(&format!(
            "  {{\n    name: \"{}\",\n    description: {},\n    policy: {{\n      approval: {},\n      touchesNetwork: {},\n      destructive: {},\n      writes: {},\n    }},\n  }},\n",
            tool.name, description, approval, tool.policy.touches_network, tool.policy.destructive, writes
        ));
    }
    out.push_str("] as const;\n\nexport const AGENT_TOOL_PROTOCOL_VERSION = ");
    out.push_str(&agent_tools::PROTOCOL_VERSION.to_string());
    out.push_str(";\n");
    out
}

fn main() {
    let manifest = agent_tools::manifest();
    for tool in &manifest {
        tool.invariants_hold()
            .unwrap_or_else(|err| panic!("refusing to generate an invalid contract — {err}"));
    }

    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../..");
    let shared = root.join("packages/shared-schema");

    write(&shared.join("agent-tools.json"), &json(&agent_tools::canonical_document()));
    write(
        &shared.join("agent-tools.anthropic.json"),
        &json(&agent_tools::anthropic_tool_defs(&manifest)),
    );
    write(
        &shared.join("agent-tools.openai.json"),
        &json(&agent_tools::openai_tool_defs(&manifest)),
    );
    write(
        &root.join("packages/desktop/src/generated/agentTools.ts"),
        &typescript(&manifest),
    );
}
